"""Bake versioned, documented input transforms. Build-time dependency: opencolorio==2.5.2."""
from pathlib import Path
import json, hashlib
import numpy as np
import PyOpenColorIO as ocio
root=Path(__file__).resolve().parents[1]/'public/video-color'
root.mkdir(parents=True,exist_ok=True)
config_name='studio-config-v4.0.0_aces-v2.0_ocio-v2.5'
config=ocio.Config.CreateFromBuiltinConfig(config_name)
spaces=[('slog3-cine','Sony S-Log3 / S-Gamut3.Cine','S-Log3 S-Gamut3.Cine'),('slog3','Sony S-Log3 / S-Gamut3','S-Log3 S-Gamut3'),('clog3','Canon Log 3 / Cinema Gamut D55','CanonLog3 CinemaGamut D55'),('clog2','Canon Log 2 / Cinema Gamut D55','CanonLog2 CinemaGamut D55'),('red-log3g10','RED Log3G10 / REDWideGamutRGB','Log3G10 REDWideGamutRGB'),('vlog','Panasonic V-Log / V-Gamut','V-Log V-Gamut'),('dlog','DJI D-Log / D-Gamut','D-Log D-Gamut'),('apple-log','Apple Log','Apple Log'),('bmd-film5','Blackmagic Film / Wide Gamut Gen 5','BMDFilm WideGamut Gen5'),('arri-logc3','ARRI LogC3 / EI800','ARRI LogC3 (EI800)'),('arri-logc4','ARRI LogC4','ARRI LogC4'),('srgb','Photo sRGB','sRGB Encoded Rec.709 (sRGB)')]
size=33
base=np.array([[r/(size-1),g/(size-1),b/(size-1)] for b in range(size) for g in range(size) for r in range(size)],dtype=np.float32)
manifest={'ocio':ocio.GetVersion(),'config':config_name,'output':'Rec.1886 Rec.709 SDR, 100 nits','cubeSize':size,'spaces':[{'id':'rec709','name':'Rec.709 SDR (déjà développé)'}]}
for identifier,label,source in spaces:
 if identifier=='srgb':processor=config.getProcessor(source,'Gamma 2.4 Encoded Rec.709')
 else:
  transform=ocio.DisplayViewTransform(src=source,display='Rec.1886 Rec.709 - Display',view='ACES 2.0 - SDR 100 nits (Rec.709)')
  processor=config.getProcessor(transform)
 values=base.copy();processor.getDefaultCPUProcessor().applyRGB(values)
 assert np.isfinite(values).all()
 p=root/(identifier+'.cube')
 with p.open('w') as f:
  f.write(f'# Generated by OpenColorIO {ocio.GetVersion()} / {config_name}\n# Input: {source}; Output: Rec.1886 Rec.709 SDR\nLUT_3D_SIZE {size}\nDOMAIN_MIN 0 0 0\nDOMAIN_MAX 1 1 1\n')
  for row in values:f.write(' '.join(f'{float(x):.8f}' for x in row)+'\n')
 manifest['spaces'].append({'id':identifier,'name':label,'source':source,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()})
 # Independent reference samples retained for engine regression tests.
 samples=np.array([[.2,.2,.2],[.4,.4,.4],[.65,.3,.25],[.3,.6,.25],[.25,.3,.7]],dtype=np.float32)
 processor.getDefaultCPUProcessor().applyRGB(samples)
 manifest.setdefault('references',{})[identifier]=samples.tolist()
(root/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Generated',len(spaces),'input transforms with OpenColorIO',ocio.GetVersion())
